# ========== ФУНКЦИИ ПАРСЕРА ==========
def get_threat_level(text):
    text_lower = text.lower()
    if 'отбой' in text_lower or 'опасность миновала' in text_lower:
        return {'level': 0, 'status': 'Отбой / Спокойно', 'type': 'safe'}
    elif re.search(r'ракетн', text_lower):
        return {'level': 90, 'status': 'Ракетная опасность', 'type': 'missile'}
    elif re.search(r'бпла|беспилотн|дрон', text_lower):
        return {'level': 80, 'status': 'Атака БПЛА', 'type': 'drone'}
    return None

def parse_and_update():
    print("🔄 Проверка каналов...")
    
    current_status = {}
    if os.path.exists(STATUS_FILE):
        with open(STATUS_FILE, 'r', encoding='utf-8') as f:
            current_status = json.load(f)
    
    for channel in CHANNELS:
        try:
            url = f'https://t.me/s/{channel}'
            headers = {'User-Agent': 'Mozilla/5.0'}
            response = requests.get(url, headers=headers, timeout=15)
            
            if response.status_code != 200:
                print(f"  ⚠️ {channel}: ошибка {response.status_code}")
                continue
            
            soup = BeautifulSoup(response.text, 'html.parser')
            first_post = soup.find('div', class_='tgme_widget_message_text')
            
            if not first_post:
                continue
            
            post_text = first_post.get_text(strip=True)
            print(f"  📨 {channel}: {post_text[:80]}...")
            
            region = None
            for key, region_name in REGIONS_MAP.items():
                if key in post_text.lower():
                    region = region_name
                    break
            
            if not region:
                print(f"  ❌ Регион не найден")
                continue
            
            threat = get_threat_level(post_text)
            if not threat:
                print(f"  ⚠️ Тип угрозы не определён")
                continue
            
            current_status[region] = {
                'level': threat['level'],
                'status': threat['status'],
                'type': threat['type'],
                'last_update': datetime.now().isoformat()
            }
            print(f"  ✅ {region}: {threat['status']}")
            
        except Exception as e:
            print(f"  ❌ Ошибка {channel}: {e}")
    
    with open(STATUS_FILE, 'w', encoding='utf-8') as f:
        json.dump(current_status, f, ensure_ascii=False, indent=2)
    
    print("💾 Статус сохранён")

if __name__ == "__main__":
    print("🚀 Запуск парсера...")
    parse_and_update()
    print("✅ Готово")
